"""Generate the built-in example molecules for MATTER LAB.

Each structure is embedded with RDKit's ETKDG and relaxed with MMFF94, so the coordinates are a real
computed geometry (not typed in by hand and not experimental). Run from the repository root:

    .venv\\Scripts\\python.exe tools\\data\\build_examples.py
"""

from __future__ import annotations

import json
import pathlib
from datetime import datetime, timezone

import rdkit
from rdkit import Chem
from rdkit.Chem import AllChem, rdMolTransforms

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "packages" / "core" / "src" / "examples" / "examples.generated.ts"

# (id, name, SMILES, one-line description without numeric claims)
MOLECULES = [
    ("water", "Water", "O", "The bent triatomic molecule behind hydrogen bonding."),
    ("methane", "Methane", "C", "The simplest hydrocarbon; a regular tetrahedron."),
    ("benzene", "Benzene", "c1ccccc1", "The archetypal aromatic ring with six delocalised bonds."),
    ("ammonia", "Ammonia", "N", "A trigonal pyramid with one lone pair on nitrogen."),
    ("carbon-dioxide", "Carbon dioxide", "O=C=O", "A linear molecule with two double bonds."),
    ("ethene", "Ethene", "C=C", "The simplest alkene; planar around its double bond."),
    ("ethyne", "Ethyne", "C#C", "The simplest alkyne; linear around its triple bond."),
    ("ethanol", "Ethanol", "CCO", "A small alcohol with a freely rotating carbon chain."),
    ("acetic-acid", "Acetic acid", "CC(=O)O", "The carboxylic acid of vinegar."),
    ("ammonium", "Ammonium ion", "[NH4+]", "A tetrahedral cation carrying a formal positive charge."),
    ("glycine", "Glycine", "NCC(=O)O", "The smallest amino acid, shown in its neutral form."),
    ("cyclohexane", "Cyclohexane", "C1CCCCC1", "A saturated six-membered ring in its chair conformation."),
    ("adamantane", "Adamantane", "C1C2CC3CC1CC(C2)C3", "A rigid cage built from fused chair rings."),
    ("glucose", "Glucose", "OC[C@H]1O[C@@H](O)[C@H](O)[C@@H](O)[C@@H]1O", "Beta-D-glucopyranose, the ring form of the sugar."),
    ("aspirin", "Aspirin", "CC(=O)Oc1ccccc1C(=O)O", "Acetylsalicylic acid: an ester and a carboxylic acid on a benzene ring."),
    ("caffeine", "Caffeine", "Cn1cnc2c1c(=O)n(C)c(=O)n2C", "A fused bicyclic purine with three methyl groups."),
]


def build(smiles: str):
    mol = Chem.AddHs(Chem.MolFromSmiles(smiles))
    if AllChem.EmbedMolecule(mol, randomSeed=20261113) != 0:
        raise RuntimeError(f"embedding failed for {smiles}")
    props = AllChem.MMFFGetMoleculeProperties(mol)
    if props is None:
        raise RuntimeError(f"MMFF94 has no parameters for {smiles}")
    status = AllChem.MMFFOptimizeMolecule(mol, maxIters=5000)
    if status != 0:
        raise RuntimeError(f"MMFF94 optimisation did not converge for {smiles}")
    rdMolTransforms.CanonicalizeConformer(mol.GetConformer())
    return mol


def main() -> None:
    records = []
    for ident, name, smiles, description in MOLECULES:
        mol = build(smiles)
        conf = mol.GetConformer()
        atoms = []
        for atom in mol.GetAtoms():
            p = conf.GetAtomPosition(atom.GetIdx())
            atoms.append([atom.GetAtomicNum(), atom.GetFormalCharge(), round(p.x, 4), round(p.y, 4), round(p.z, 4)])
        bonds = [[b.GetBeginAtomIdx(), b.GetEndAtomIdx(), b.GetBondTypeAsDouble()] for b in mol.GetBonds()]
        records.append(
            {
                "id": ident,
                "name": name,
                "smiles": Chem.MolToSmiles(Chem.RemoveHs(mol)),
                "description": description,
                "atoms": atoms,
                "bonds": bonds,
            }
        )

    provenance = {
        "source": "RDKit ETKDG embedding followed by MMFF94 optimisation",
        "version": f"RDKit {rdkit.__version__}",
        "retrieved": datetime.now(timezone.utc).date().isoformat(),
        "notes": "Computed gas-phase force-field geometries. They are close to, but not the same as, experimental structures.",
        "citations": [
            {
                "authors": "T. A. Halgren",
                "title": "Merck molecular force field. I. Basis, form, scope, parameterization, and performance of MMFF94",
                "source": "Journal of Computational Chemistry 17, 490-519",
                "year": 1996,
            },
            {
                "authors": "S. Riniker, G. A. Landrum",
                "title": "Better informed distance geometry: using what we know to improve conformation generation",
                "source": "Journal of Chemical Information and Modeling 55, 2562-2574",
                "year": 2015,
                "doi": "10.1021/acs.jcim.5b00654",
            },
        ],
    }

    lines = [
        "// AUTO-GENERATED by tools/data/build_examples.py. Do not edit by hand; re-run the script instead.",
        "import type { Provenance } from '../provenance';",
        "import type { ExampleRecord } from './types';",
        "",
        f"export const EXAMPLE_PROVENANCE: Provenance = {json.dumps(provenance, indent=2)};",
        "",
        "// atoms: [atomic number, formal charge, x, y, z] in angstrom; bonds: [atom index, atom index, order]",
        "export const EXAMPLE_RECORDS: readonly ExampleRecord[] = [",
    ]
    lines += [f"  {json.dumps(r)}," for r in records]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(records)} molecules, RDKit {rdkit.__version__})")
    for r in records:
        print(f"  {r['id']:<16} {len(r['atoms']):>3} atoms  {r['smiles']}")


if __name__ == "__main__":
    main()
