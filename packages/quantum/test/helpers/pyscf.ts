import { readJsonFixture } from './crawford';

export interface PyscfMolecule {
  readonly name: string;
  readonly orientation: 'general' | 'canonical';
  readonly charge: number;
  readonly atoms: { readonly z: number; readonly position: [number, number, number] }[];
  readonly nBasis: number;
  readonly nElectrons: number;
  readonly nOccupied: number;
  readonly converged: boolean;
  readonly energy: {
    readonly total: number;
    readonly electronic: number;
    readonly nuclearRepulsion: number;
    readonly kinetic: number;
    readonly nuclearAttraction: number;
    readonly twoElectron: number;
  };
  readonly orbitalEnergies: number[];
  readonly mullikenCharges: number[];
  readonly dipoleAu: [number, number, number];
  readonly dipoleOriginBohr: [number, number, number];
  readonly internalStable: boolean | null;
  readonly externalStable: boolean | null;
  readonly coreGuess: { readonly converged: boolean; readonly totalEnergy: number };
  readonly builtinSto3gTotalEnergy: number | null;
}

export interface PyscfIntegrals {
  readonly name: string;
  readonly orientation: string;
  /** '<atom index>:<shell>' for every PySCF basis function, e.g. '0:2px'. */
  readonly aoLabels: string[];
  readonly overlap: number[][];
  readonly kinetic: number[][];
  readonly nuclearAttraction: number[][];
  /** <mu| x |nu>, <mu| y |nu>, <mu| z |nu> about the coordinate origin, in bohr. */
  readonly position: number[][][];
  readonly eri: number[];
}

export interface PyscfFields {
  readonly name: string;
  readonly orientation: string;
  readonly pointsAngstrom: [number, number, number][];
  readonly density: number[];
  readonly esp: number[];
  /** orbitals[i][p]: molecular orbital i at point p. */
  readonly orbitals: number[][];
}

export interface PyscfFixture {
  readonly generated: string;
  readonly versions: { readonly pyscf: string; readonly numpy: string; readonly python: string; readonly platform: string };
  readonly bohrToAngstrom: number;
  readonly basis: { readonly name: string; readonly sha256: string };
  readonly molecules: PyscfMolecule[];
  readonly integrals: PyscfIntegrals[];
  readonly fields: PyscfFields[];
}

let cached: PyscfFixture | undefined;

/** The PySCF reference fixture generated by tools/gen_reference.py. */
export function pyscfFixture(): PyscfFixture {
  cached ??= readJsonFixture<PyscfFixture>('pyscf_reference.json');
  return cached;
}

export function findMolecule(name: string, orientation: 'general' | 'canonical' = 'general'): PyscfMolecule {
  const molecule = pyscfFixture().molecules.find((m) => m.name === name && m.orientation === orientation);
  if (!molecule) throw new Error(`The PySCF fixture has no entry for ${name} (${orientation}).`);
  return molecule;
}

export function toInput(molecule: PyscfMolecule) {
  return { atoms: molecule.atoms.map((atom) => ({ z: atom.z, position: atom.position })), charge: molecule.charge };
}
