#!/usr/bin/env node
/**
 * Generates the data tables of `@matterlab/forcefield` from the RDKit source files vendored under
 * `tools/rdkit-src/` (see `fetch_rdkit_sources.mjs`). Nothing in the output is typed by hand:
 *
 *   src/generated/uffParams.generated.ts      <- Code/ForceField/UFF/Params.cpp  (defaultParamData)
 *   src/generated/rdkitElements.generated.ts  <- Code/GraphMol/atomic_data.cpp   (periodicTableAtomData)
 *
 * Numeric tokens are copied into the output exactly as they are spelled in the RDKit source, so no
 * value passes through a float formatter. Each input file is checked against the SHA-256 recorded
 * in `tools/rdkit-src/MANIFEST.json` before it is parsed.
 *
 * Usage (from the repository root, after `.\env.ps1`):
 *   node packages/forcefield/tools/gen_uff_params.mjs
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC_DIR = join(HERE, 'rdkit-src');
const OUT_DIR = join(HERE, '..', 'src', 'generated');

const manifest = JSON.parse(readFileSync(join(SRC_DIR, 'MANIFEST.json'), 'utf8'));

function readVendored(rel) {
  const text = readFileSync(join(SRC_DIR, ...rel.split('/')), 'utf8');
  const sha256 = createHash('sha256').update(text).digest('hex');
  const expected = manifest.files[rel]?.sha256;
  if (sha256 !== expected) {
    throw new Error(`${rel}: SHA-256 ${sha256} does not match MANIFEST.json (${expected}). Re-run fetch_rdkit_sources.mjs.`);
  }
  return { text, sha256 };
}

const NUMBER_TOKEN = /^-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?$/;
function numberToken(token, context) {
  if (!NUMBER_TOKEN.test(token) || !Number.isFinite(Number(token))) {
    throw new Error(`Not a number: ${JSON.stringify(token)} (${context})`);
  }
  // Keep the source spelling, but make sure it is a valid TypeScript literal ("1." and ".5" are not
  // used by RDKit; reject them rather than rewrite them).
  if (/^-?\d+\.$/.test(token) || /^-?\./.test(token)) {
    throw new Error(`Unsupported number spelling ${JSON.stringify(token)} (${context})`);
  }
  // Leading zeros would be read as legacy octal by JavaScript.
  if (/^-?0\d/.test(token)) throw new Error(`Leading zero in ${JSON.stringify(token)} (${context})`);
  return token;
}

/** Version string as RDKit reports it, e.g. Release_2026_09_2 -> 2026.09.2 */
function versionFromTag(tag) {
  const m = /^Release_(\d{4})_(\d{2})_(\d+)(?:_?([a-z]\d+))?$/.exec(tag);
  if (!m) throw new Error(`Cannot derive an RDKit version from tag ${tag}`);
  return `${m[1]}.${m[2]}.${m[3]}${m[4] ?? ''}`;
}

const RDKIT_VERSION = versionFromTag(manifest.tag);

