// ---------------------------------------------------------------------------------------------
// RDKit periodic-table data used by its valence model
// ---------------------------------------------------------------------------------------------

/** Concatenates the raw string literals R"DAT( ... )DAT" that follow `marker`, up to the closing `;`. */
function readRawStringLiterals(text, marker, file) {
  const start = text.indexOf(marker);
  if (start < 0) throw new Error(`${file}: ${JSON.stringify(marker)} not found`);
  let i = start + marker.length;
  let out = '';
  let nLiterals = 0;
  for (;;) {
    while (i < text.length && /\s/.test(text[i])) i++;
    if (text.startsWith('//', i)) {
      i = text.indexOf('\n', i);
      if (i < 0) throw new Error(`${file}: unterminated comment`);
      continue;
    }
    if (text[i] === ';') break;
    const open = 'R"DAT(';
    const close = ')DAT"';
    if (!text.startsWith(open, i)) throw new Error(`${file}: expected ${open} at offset ${i}, found ${JSON.stringify(text.slice(i, i + 20))}`);
    const end = text.indexOf(close, i + open.length);
    if (end < 0) throw new Error(`${file}: unterminated raw string`);
    out += text.slice(i + open.length, end);
    i = end + close.length;
    nLiterals++;
  }
  if (nLiterals === 0) throw new Error(`${file}: no raw string literals after ${JSON.stringify(marker)}`);
  return out;
}

const ATOMIC_REL = 'Code/GraphMol/atomic_data.cpp';
const atomicSrc = readVendored(ATOMIC_REL);
const atomicText = readRawStringLiterals(atomicSrc.text, 'const std::string periodicTableAtomData =', ATOMIC_REL);

// RDKit tokenises each line on spaces and tabs (boost::char_separator, which drops empty tokens):
// atomic number, symbol, row, rCov, rB0, rVdw, mass, outer-shell electrons, most common isotope,
// its mass, then the list of allowed valences (-1 = anything).
const elements = new Map();
for (const line of atomicText.split('\n')) {
  const tok = line.split(/[ \t]+/).filter((t) => t !== '');
  if (tok.length === 0) continue;
  if (tok.length < 11) throw new Error(`${ATOMIC_REL}: short line ${JSON.stringify(line)}`);
  const z = Number(tok[0]);
  if (!Number.isInteger(z) || z < 0) throw new Error(`${ATOMIC_REL}: bad atomic number in ${JSON.stringify(line)}`);
  const symbol = tok[1];
  const outer = Number(tok[7]);
  const valences = tok.slice(10).map((t) => Number(t));
  if (!Number.isInteger(outer) || outer < 0 || valences.some((v) => !Number.isInteger(v) || v < -1)) {
    throw new Error(`${ATOMIC_REL}: cannot parse ${JSON.stringify(line)}`);
  }
  // The first entry for an atomic number wins (RDKit keeps Uut/Uup as aliases after Nh/Mc).
  if (!elements.has(z)) elements.set(z, { z, symbol, outer, valences });
}
const maxZ = Math.max(...elements.keys());
for (let z = 0; z <= maxZ; z++) {
  if (!elements.has(z)) throw new Error(`${ATOMIC_REL}: element ${z} missing`);
}
if (maxZ !== 118) throw new Error(`${ATOMIC_REL}: expected elements 0..118, found up to ${maxZ}`);
const els = Array.from({ length: maxZ + 1 }, (_, z) => elements.get(z));

function chunk(items, perLine) {
  const lines = [];
  for (let i = 0; i < items.length; i += perLine) lines.push(`  ${items.slice(i, i + perLine).join(', ')},`);
  return lines.join('\n');
}

const elementsOut = `${header(ATOMIC_REL, atomicSrc.sha256, "The parts of RDKit's periodic table that its valence, conjugation and hybridisation perception use.")}
/** Where the tables below came from. */
export const RDKIT_ELEMENTS_PROVENANCE = {
  rdkitVersion: '${RDKIT_VERSION}',
  rdkitTag: '${manifest.tag}',
  rdkitCommit: '${manifest.commit}',
  sourceFile: '${ATOMIC_REL}',
  sourceSha256: '${atomicSrc.sha256}',
  retrieved: '${manifest.retrieved}',
  license: 'BSD-3-Clause',
} as const;

/** Largest atomic number RDKit knows (\`PeriodicTable::getMaxAtomicNumber\`). Index 0 is the dummy atom "*". */
export const RDKIT_MAX_ATOMIC_NUMBER = ${maxZ};

/** Element symbols indexed by atomic number (\`PeriodicTable::getElementSymbol\`). */
// prettier-ignore
export const RDKIT_ELEMENT_SYMBOLS: readonly string[] = [
${chunk(els.map((e) => `'${e.symbol}'`), 12)}
];

/** Outer-shell electron counts indexed by atomic number (\`PeriodicTable::getNouterElecs\`). */
// prettier-ignore
export const RDKIT_OUTER_ELECTRONS: readonly number[] = [
${chunk(els.map((e) => String(e.outer)), 20)}
];

/**
 * Allowed valences indexed by atomic number (\`PeriodicTable::getValenceList\`). A trailing -1 means
 * "anything goes"; the first entry is the default valence (\`PeriodicTable::getDefaultValence\`).
 */
// prettier-ignore
export const RDKIT_VALENCE_LISTS: readonly (readonly number[])[] = [
${chunk(els.map((e) => `[${e.valences.join(', ')}]`), 8)}
];
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'uffParams.generated.ts'), paramsOut);
writeFileSync(join(OUT_DIR, 'rdkitElements.generated.ts'), elementsOut);
console.log(`RDKit ${RDKIT_VERSION} (${manifest.tag}, ${manifest.commit})`);
console.log(`  uffParams.generated.ts: ${paramRows.length} atom types, lambda=${LAMBDA}, G=${G}`);
console.log(`  rdkitElements.generated.ts: elements 0..${maxZ}`);
