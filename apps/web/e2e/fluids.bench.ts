import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { expect, test } from '@playwright/test';
import { FluidsLab } from './fluids-lab';
import type { PerfSnapshot } from './fluids-lab';

/**
 * Rendering benchmark for `lab/fluids`, measured in the real dev harness on this machine's GPU. It
 * measures; the only assertions are that frames actually rendered and the page logged no errors,
 * matching the main application's `render.bench.ts` convention — a slow machine cannot fail this.
 * Run with `npx playwright test -c playwright.bench.config.ts e2e/fluids.bench.ts`. Results go to
 * docs/benchmarks/fluids-benchmark.{md,json}.
 */

const OUT = fileURLToPath(new URL('../../../docs/benchmarks/', import.meta.url));
const QUALITIES = ['efficient', 'balanced', 'quality'] as const;
const SCENARIOS = ['clear-liquid', 'tinted-liquid', 'burette-levels', 'swirling'] as const;
const WARMUP_MS = 600;
const MEASURE_MS = 2500;

interface Row extends PerfSnapshot {
  scenario: string;
  quality: string;
}

let lab: FluidsLab;

test.beforeEach(async ({ page }) => {
  lab = new FluidsLab(page);
  await lab.open();
});

test('fluids scenario x quality benchmark', async () => {
  const rows: Row[] = [];
  const device = await lab.page.evaluate(() => {
    const canvas = document.querySelector('canvas') as HTMLCanvasElement;
    const gl = canvas.getContext('webgl2');
    const info = gl?.getExtension('WEBGL_debug_renderer_info');
    return {
      renderer: info && gl ? String(gl.getParameter(info.UNMASKED_RENDERER_WEBGL)) : 'unknown',
      cores: navigator.hardwareConcurrency || 0,
    };
  });

  for (const scenario of SCENARIOS) {
    await lab.setScenario(scenario);
    for (const quality of QUALITIES) {
      await lab.eval(`lab.getState().setQualityTier(${JSON.stringify(quality)});`);
      await lab.page.waitForTimeout(WARMUP_MS);
      await lab.resetPerf();
      await lab.page.waitForTimeout(MEASURE_MS);
      const snapshot = await lab.perfSnapshot();
      rows.push({ scenario, quality, ...snapshot });
    }
  }

  // The titration scene's extra moving parts (droplet stream, live color/meniscus updates).
  await lab.setScenario('endpoint-titration');
  for (const quality of QUALITIES) {
    await lab.eval(`lab.getState().setQualityTier(${JSON.stringify(quality)});`);
    await lab.setDripping(true);
    await lab.page.waitForTimeout(WARMUP_MS);
    await lab.resetPerf();
    await lab.page.waitForTimeout(MEASURE_MS);
    const snapshot = await lab.perfSnapshot();
    rows.push({ scenario: 'endpoint-titration (dripping)', quality, ...snapshot });
    await lab.setDripping(false);
  }

  lab.expectNoProblems();
  expect(rows.every((r) => r.framesRendered > 0)).toBe(true);

  await mkdir(OUT, { recursive: true });
  await writeFile(`${OUT}fluids-benchmark.json`, JSON.stringify({ device, measuredAt: new Date().toISOString(), rows }, null, 2));

  const fmt = (n: number | null, digits = 1) => (n === null ? 'n/a' : n.toFixed(digits));
  const lines = [
    '# lab/fluids rendering benchmark',
    '',
    '<!-- Generated by apps/web/e2e/fluids.bench.ts. Do not edit by hand; run the benchmark again. -->',
    '',
    `Measured ${new Date().toISOString()} in the running dev harness (\`/fluids-lab.html\`). Raw numbers: [fluids-benchmark.json](fluids-benchmark.json).`,
    '',
    '## Machine',
    '',
    `- Graphics: ${device.renderer}`,
    `- Logical cores: ${device.cores}`,
    '',
    '## How to read the numbers',
    '',
    "- Each row is one scenario at one quality tier, OrbitControls untouched (the camera is static; these numbers are the vessels' own steady-state cost, not a camera-move stress test — see render.bench.ts in the main app for that style of test).",
    `- ${WARMUP_MS} ms warm-up (lets shaders compile and any transmission render target allocate), then ${MEASURE_MS} ms measured.`,
    '- "efficient"/"balanced" use the alpha-blended glass and liquid fallback or a transmissive glass shell; "quality" adds finer lathe/meniscus geometry on top of the same transmissive glass (no tier currently enables liquid transmission — see quality/fluidQuality.ts).',
    '- GPU ms is `n/a` where the browser exposes no `EXT_disjoint_timer_query_webgl2`.',
    '',
    '| Scenario | Quality | fps | Frame ms | GPU ms | CPU ms | Draw calls | Triangles | Pixel ratio |',
    '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...rows.map(
      (r) =>
        `| ${r.scenario} | ${r.quality} | ${fmt(r.fps)} | ${fmt(r.frameMs, 2)} | ${fmt(r.gpuMs, 2)} | ${fmt(r.cpuMs, 2)} | ${r.drawCalls} | ${r.triangles} | ${r.pixelRatio.toFixed(2)} |`,
    ),
    '',
  ];
  await writeFile(`${OUT}fluids-benchmark.md`, lines.join('\n'));
});
