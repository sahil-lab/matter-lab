"""Compound catalogue: lookup and exact, substructure and similarity search.

The searches run in the science service with RDKit on rows loaded from PostgreSQL. PostgreSQL has
no chemistry cartridge here; it stores structures and fingerprints and answers the exact lookups.
"""

from __future__ import annotations

import re
from collections import Counter
from datetime import datetime
from typing import Any, Literal
from uuid import UUID

from fastapi import APIRouter, Query
from pydantic import BaseModel, ConfigDict, Field
from rdkit import Chem

from ..catalogue import search
from ..chem import rdlog
from ..chem.structure import MAX_STRUCTURE_CHARS, identity
from ..errors import ApiError, error_responses, not_found
from ..provenance import PROVENANCE_COLUMNS, EvidenceLevel, Provenance, evidence_for, provenance_from_row
from .common import Ctx, EngineStamp, StructureInput, engine_stamp, require_structure, utc_now
from .reference import SourcedPage, collect_sources, source_ref

router = APIRouter(prefix="/v1/compounds", tags=["catalogue"])

_SUMMARY_COLUMNS = (
    "c.id, c.name, c.iupac_name, c.canonical_smiles, c.inchikey, c.molecular_formula, c.molecular_weight_g_per_mol, "
    "c.monoisotopic_mass_u, c.formal_charge, c.external_ids"
)

_FORMULA_TOKEN = re.compile(r"([A-Z][a-z]?)(\d*)")
_FORMULA = re.compile(r"^((?:[A-Z][a-z]?\d*)+)([+-]\d*)?$")


def hill_formula(text: str) -> str:
    """Rewrites a simple formula (element symbols and counts, optional trailing charge) in Hill
    order, the notation stored in the catalogue. Anything else is returned unchanged."""
    cleaned = text.strip().replace(" ", "")
    match = _FORMULA.match(cleaned)
    if not match:
        return cleaned
    counts: Counter[str] = Counter()
    for symbol, number in _FORMULA_TOKEN.findall(match.group(1)):
        counts[symbol] += int(number) if number else 1
    if "C" in counts:
        order = ["C"] + (["H"] if "H" in counts else []) + sorted(s for s in counts if s not in ("C", "H"))
    else:
        order = sorted(counts)
    return "".join(f"{s}{counts[s] if counts[s] != 1 else ''}" for s in order) + (match.group(2) or "")


class CompoundSummary(BaseModel):
    id: UUID
    name: str
    iupac_name: str | None
    canonical_smiles: str = Field(description="RDKit canonical isomeric SMILES.")
    inchikey: str
    molecular_formula: str
    molecular_weight_g_per_mol: float
    monoisotopic_mass_u: float
    formal_charge: int
    external_ids: dict[str, Any] = Field(description="Identifiers in other databases, e.g. `pubchem_cid`.")
    evidence: EvidenceLevel = Field(
        description=(
            "How the record (name and structure) was obtained, from the kind of its source: `reference` for a published dataset or service, "
            "`user-input` for a compound imported from a workbook. Canonical SMILES, InChIKey, formula and masses are always computed from the "
            "structure by RDKit."
        )
    )


class CompoundListItem(CompoundSummary):
    source: str


class Synonym(BaseModel):
    name: str
    kind: Literal["preferred", "iupac", "query", "synonym"]


class Compound(CompoundSummary):
    inchi: str
    molblock: str = Field(description="2D depiction molfile generated by RDKit (not a 3D geometry). Atom order matches the canonical SMILES.")
    heavy_atom_count: int
    synonyms: list[Synonym]
    fingerprint_params: dict[str, Any] = Field(description="Parameters of the fingerprints stored with the compound.")
    morgan_fingerprint_on_bits: int
    derived_by: EngineStamp = Field(description="Engine that computed every structure-derived field.")
    source_url: str | None
    source_record: dict[str, Any] | None = Field(description="The record as retrieved from the source.")
    provenance: Provenance
    created_at: datetime
    updated_at: datetime


class SearchScope(BaseModel):
    """What exactly was searched. A search answers for this catalogue only."""

    catalog_key: str
    catalog_title: str
    description: str
    records_searched: int
    searched_at: datetime
    method: str
    engine: EngineStamp
    note: str


def scope(records: int, method: str) -> SearchScope:
    return SearchScope(
        catalog_key=search.CATALOG_KEY,
        catalog_title=search.CATALOG_TITLE,
        description=search.CATALOG_DESCRIPTION,
        records_searched=records,
        searched_at=utc_now(),
        method=method,
        engine=engine_stamp(),
        note="The result covers only the records of this catalogue at the stated time. The absence of a match says nothing about other databases or the literature.",
    )


class QueryStructure(BaseModel):
    canonical_smiles: str
    inchikey: str | None
    molecular_formula: str


def _query(mol: Chem.Mol) -> QueryStructure:
    ident = identity(mol)
    return QueryStructure(canonical_smiles=ident["canonical_smiles"], inchikey=ident["inchikey"], molecular_formula=ident["molecular_formula"])


def _summaries(ctx: Any, ids: list[UUID]) -> dict[UUID, CompoundSummary]:
    if not ids:
        return {}
    rows = ctx.db.fetch_all(f"SELECT {_SUMMARY_COLUMNS}, ds.kind AS ds_kind FROM compounds c JOIN data_sources ds ON ds.id = c.source_id WHERE c.id = ANY(%s)", (ids,))
    return {r["id"]: CompoundSummary(**{k: v for k, v in r.items() if k != "ds_kind"}, evidence=evidence_for(r["ds_kind"])) for r in rows}


@router.get("", response_model=SourcedPage[CompoundListItem], responses=error_responses(422), summary="List or look up compounds")
def list_compounds(
    ctx: Ctx,
    inchikey: str | None = Query(default=None, pattern="^[A-Z]{14}-[A-Z]{10}-[A-Z]$", description="Exact standard InChIKey."),
    name: str | None = Query(default=None, min_length=1, max_length=500, description="Exact name, case-insensitive: preferred name, IUPAC name or a stored synonym."),
    formula: str | None = Query(default=None, min_length=1, max_length=200, description="Exact molecular formula. Element order does not matter (it is rewritten in Hill notation)."),
    pubchem_cid: int | None = Query(default=None, ge=1, description="PubChem compound identifier."),
    q: str | None = Query(default=None, min_length=2, max_length=200, description="Case-insensitive fragment of a name or synonym."),
    limit: int = Query(default=50, ge=1, le=500),
    offset: int = Query(default=0, ge=0),
) -> SourcedPage[CompoundListItem]:
    """Filters combine with AND. All matching is done by PostgreSQL on stored values."""
    clauses: list[str] = []
    params: list[Any] = []
    if inchikey is not None:
        clauses.append("c.inchikey = %s")
        params.append(inchikey)
    if name is not None:
        clauses.append("EXISTS (SELECT 1 FROM compound_synonyms s WHERE s.compound_id = c.id AND s.name_normalized = lower(btrim(%s)))")
        params.append(name)
    if formula is not None:
        clauses.append("c.molecular_formula = %s")
        params.append(hill_formula(formula))
    if pubchem_cid is not None:
        clauses.append("c.external_ids @> %s::jsonb")
        params.append(f'{{"pubchem_cid": {int(pubchem_cid)}}}')
    if q is not None:
        clauses.append("EXISTS (SELECT 1 FROM compound_synonyms s WHERE s.compound_id = c.id AND s.name_normalized LIKE %s)")
        escaped = q.strip().lower().replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        params.append(f"%{escaped}%")
    where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
    with ctx.db.connection() as conn:
        total = conn.execute(f"SELECT count(*) AS n FROM compounds c {where}", params).fetchone()
        rows = conn.execute(
            f"SELECT {_SUMMARY_COLUMNS}, {PROVENANCE_COLUMNS} FROM compounds c JOIN data_sources ds ON ds.id = c.source_id "
            f"{where} ORDER BY lower(c.name), c.id LIMIT %s OFFSET %s",
            [*params, limit, offset],
        ).fetchall()
    items = [CompoundListItem(**{k: v for k, v in r.items() if not k.startswith("ds_")}, evidence=evidence_for(r["ds_kind"]), source=source_ref(r)) for r in rows]
    return SourcedPage[CompoundListItem](items=items, total=int(total["n"]) if total else 0, limit=limit, offset=offset, sources=collect_sources(rows))


