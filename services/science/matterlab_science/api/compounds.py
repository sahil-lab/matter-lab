class ExactSearchRequest(BaseModel):
    model_config = ConfigDict(json_schema_extra={"examples": [{"structure": {"format": "smiles", "data": "OC(=O)c1ccccc1OC(C)=O"}}]})

    structure: StructureInput


class ExactSearchResponse(BaseModel):
    query: QueryStructure
    matches: list[CompoundSummary] = Field(description="Catalogue records with the same standard InChIKey.")
    same_connectivity: list[CompoundSummary] = Field(
        description="Records that share the first InChIKey block (same connectivity) but differ in stereochemistry, isotopes or charge state."
    )
    scope: SearchScope


@router.post("/search/exact", response_model=ExactSearchResponse, responses=error_responses(422), summary="Exact structure lookup")
def search_exact(request: ExactSearchRequest, ctx: Ctx) -> ExactSearchResponse:
    """The query is normalised by RDKit and matched on its standard InChIKey."""
    parsed = require_structure(request.structure)
    assert parsed.mol is not None
    query = _query(parsed.mol)
    if query.inchikey is None:
        raise ApiError(422, "no_inchikey", "No InChIKey could be generated for this structure, so it cannot be looked up exactly.", {"canonical_smiles": query.canonical_smiles})
    exact, related, total = ctx.catalogue.exact(query.inchikey)
    found = _summaries(ctx, [r["id"] for r in exact + related])
    return ExactSearchResponse(
        query=query,
        matches=[found[r["id"]] for r in exact if r["id"] in found],
        same_connectivity=[found[r["id"]] for r in related if r["id"] in found],
        scope=scope(total, search.EXACT_METHOD),
    )


class SubstructureQuery(BaseModel):
    format: Literal["smarts", "smiles"] = Field(description="`smarts` for a SMARTS pattern, `smiles` to use a molecule as the pattern.")
    data: str = Field(min_length=1, max_length=MAX_STRUCTURE_CHARS)


class SubstructureSearchRequest(BaseModel):
    model_config = ConfigDict(json_schema_extra={"examples": [{"query": {"format": "smarts", "data": "c1ccccc1C(=O)[OH]"}, "limit": 20}]})

    query: SubstructureQuery
    limit: int = Field(default=50, ge=1, le=500)
    offset: int = Field(default=0, ge=0)


class SubstructureMatch(BaseModel):
    compound: CompoundSummary
    matched_atom_indices: list[int] = Field(description="Atoms of the compound (in the order of its canonical SMILES and stored molblock) matched by the query atoms, first match only.")


class SubstructureSearchResponse(BaseModel):
    query_smarts: str = Field(description="The query as RDKit understood it, written as SMARTS.")
    matches: list[SubstructureMatch]
    total: int = Field(description="Number of catalogue records containing the substructure.")
    limit: int
    offset: int
    scope: SearchScope


@router.post("/search/substructure", response_model=SubstructureSearchResponse, responses=error_responses(422), summary="Substructure search")
def search_substructure(request: SubstructureSearchRequest, ctx: Ctx) -> SubstructureSearchResponse:
    text = request.query.data.strip()
    with rdlog.capture() as log:
        if request.query.format == "smarts":
            pattern = Chem.MolFromSmarts(text)
        else:
            pattern = Chem.MolFromSmiles(text)
    if pattern is None or pattern.GetNumAtoms() == 0:
        said = rdlog.messages(log) or [f"RDKit could not parse the {request.query.format.upper()} query."]
        raise ApiError(422, "invalid_query", f"RDKit could not interpret the substructure query: {'; '.join(said)}", {"format": request.query.format, "errors": said})
    hits, total, searched = ctx.catalogue.substructure(pattern, limit=request.limit, offset=request.offset)
    found = _summaries(ctx, [entry.id for entry, _ in hits])
    return SubstructureSearchResponse(
        query_smarts=Chem.MolToSmarts(pattern),
        matches=[SubstructureMatch(compound=found[entry.id], matched_atom_indices=atoms) for entry, atoms in hits if entry.id in found],
        total=total,
        limit=request.limit,
        offset=request.offset,
        scope=scope(searched, search.SUBSTRUCTURE_METHOD),
    )


class SimilaritySearchRequest(BaseModel):
    model_config = ConfigDict(json_schema_extra={"examples": [{"structure": {"format": "smiles", "data": "CC(=O)Oc1ccccc1C(=O)O"}, "threshold": 0.4, "limit": 10}]})

    structure: StructureInput
    threshold: float = Field(default=0.7, ge=0.0, le=1.0, description="Minimum Tanimoto similarity.")
    limit: int = Field(default=20, ge=1, le=500)


class SimilarityHit(BaseModel):
    compound: CompoundSummary
    similarity: float = Field(description="Tanimoto similarity of the Morgan fingerprints, 0 to 1.")


class SimilaritySearchResponse(BaseModel):
    query: QueryStructure
    threshold: float
    hits: list[SimilarityHit] = Field(description="Most similar first.")
    total_at_or_above_threshold: int
    limit: int
    scope: SearchScope


@router.post("/search/similarity", response_model=SimilaritySearchResponse, responses=error_responses(422), summary="Similarity search")
def search_similarity(request: SimilaritySearchRequest, ctx: Ctx) -> SimilaritySearchResponse:
    """Fingerprint similarity is a structural heuristic, not a statement about properties or activity."""
    parsed = require_structure(request.structure)
    assert parsed.mol is not None
    hits, total, searched = ctx.catalogue.similarity(parsed.mol, threshold=request.threshold, limit=request.limit)
    found = _summaries(ctx, [entry.id for entry, _ in hits])
    return SimilaritySearchResponse(
        query=_query(parsed.mol),
        threshold=request.threshold,
        hits=[SimilarityHit(compound=found[entry.id], similarity=score) for entry, score in hits if entry.id in found],
        total_at_or_above_threshold=total,
        limit=request.limit,
        scope=scope(searched, search.SIMILARITY_METHOD),
    )


@router.get("/{compound_id}", response_model=Compound, responses=error_responses(404, 422), summary="One compound with structure, names and provenance")
def get_compound(compound_id: UUID, ctx: Ctx) -> Compound:
    with ctx.db.connection() as conn:
        row = conn.execute(
            f"""
            SELECT {_SUMMARY_COLUMNS}, c.inchi, c.molblock, c.heavy_atom_count, c.fingerprint_params, c.derived_by, c.source_url,
                   c.source_record, c.created_at, c.updated_at, bit_count(c.morgan_fp) AS morgan_on_bits, {PROVENANCE_COLUMNS}
            FROM compounds c JOIN data_sources ds ON ds.id = c.source_id WHERE c.id = %s
            """,
            (compound_id,),
        ).fetchone()
        if row is None:
            raise not_found("compound", compound_id)
        names = conn.execute("SELECT name, kind FROM compound_synonyms WHERE compound_id = %s ORDER BY position, name", (compound_id,)).fetchall()
    data = {k: v for k, v in row.items() if not k.startswith("ds_") and k not in ("morgan_on_bits", "derived_by")}
    return Compound(
        **data,
        evidence=evidence_for(row["ds_kind"]),
        synonyms=[Synonym(**n) for n in names],
        morgan_fingerprint_on_bits=int(row["morgan_on_bits"]),
        derived_by=EngineStamp(**row["derived_by"]),
        provenance=provenance_from_row(row),
    )
