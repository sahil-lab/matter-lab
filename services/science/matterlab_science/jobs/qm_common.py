"""Shared preparation for the electronic-structure tasks (xTB, PySCF).

Turns the job input into nuclei, coordinates in angstrom, total charge and spin multiplicity, and
records honestly where the geometry came from.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import numpy as np
from rdkit import Chem
from scipy import constants

from ..chem import geometry
from ..chem.structure import RDKIT_VERSION, identity
from .kinds import ELEMENT_SYMBOLS
from .runtime import TaskFailure, Unsupported, WorkerContext
from .tasks_rdkit import parse_job_structure, starting_geometry

_MIN_DISTANCE_ANGSTROM = 0.1


def _codata_label() -> str:
    import scipy
    from scipy.constants import _codata

    years = sorted(name.rsplit("_", 1)[1] for name in dir(_codata) if name.startswith("_physical_constants_") and name.rsplit("_", 1)[1].isdigit())
    edition = f"CODATA {years[-1]} recommended values" if years else "CODATA recommended values"
    return f"{edition} as provided by scipy.constants (SciPy {scipy.__version__})"


def conversions() -> dict[str, Any]:
    """Unit conversion factors, read from SciPy's CODATA tables rather than typed in."""
    debye_in_coulomb_metre = 1e-21 / constants.c
    return {
        "source": _codata_label(),
        "hartree_to_ev": float(constants.physical_constants["Hartree energy in eV"][0]),
        "bohr_to_angstrom": float(constants.physical_constants["Bohr radius"][0] * 1e10),
        "atomic_unit_of_dipole_to_debye": float(constants.physical_constants["atomic unit of electric dipole mom."][0] / debye_in_coulomb_metre),
    }


def boltzmann_hartree_per_kelvin() -> float:
    return float(constants.physical_constants["Boltzmann constant in eV/K"][0] / constants.physical_constants["Hartree energy in eV"][0])


def elementary_charge_angstrom_to_debye() -> float:
    return float(constants.e * 1e-10 / (1e-21 / constants.c))


@dataclass
class PreparedSystem:
    numbers: list[int]
    symbols: list[str]
    positions: np.ndarray  # angstrom, shape (n, 3)
    charge: int
    multiplicity: int
    electron_count: int
    geometry: dict[str, Any]
    atom_meta: list[dict[str, Any]]
    warnings: list[str] = field(default_factory=list)
    software: dict[str, str] = field(default_factory=dict)

    def atoms(self, positions: np.ndarray | None = None) -> list[dict[str, Any]]:
        coords = self.positions if positions is None else positions
        records = []
        for index, (symbol, number, meta) in enumerate(zip(self.symbols, self.numbers, self.atom_meta)):
            x, y, z = (float(v) for v in coords[index])
            records.append({"index": index, "element": symbol, "atomic_number": number, "x": x, "y": y, "z": z, **meta})
        return records


def prepare_system(job_input: dict[str, Any], seed: int, ctx: WorkerContext) -> PreparedSystem:
    structure = job_input["structure"]
    warnings: list[str] = []
    software: dict[str, str] = {}

    if structure["format"] == "atoms":
        symbols = [atom["element"] for atom in structure["atoms"]]
        numbers = [ELEMENT_SYMBOLS[symbol] for symbol in symbols]
        positions = np.array([[atom["x"], atom["y"], atom["z"]] for atom in structure["atoms"]], dtype=float)
        default_charge = 0
        default_multiplicity = None
        geometry_source = {"source": "input-coordinates", "description": "Cartesian coordinates given in the request.", "hydrogens_added": 0}
        atom_meta: list[dict[str, Any]] = [{} for _ in symbols]
    else:
        parsed = parse_job_structure(structure)
        assert parsed.mol is not None
        software["rdkit"] = RDKIT_VERSION
        full, conf_id, geometry_source, warnings = starting_geometry(parsed.mol, seed)
        if geometry_source["source"] == "generated":
            selection = geometry.select_force_field(full, conf_id, "auto")
            if selection.setup is not None:
                cleanup = geometry.minimise(selection.setup, max_iterations=2000)
                geometry_source["cleanup_force_field"] = cleanup.force_field
                geometry_source["cleanup_converged"] = cleanup.converged
                geometry_source["description"] += f" It was cleaned up with the {cleanup.force_field} force field."
            else:
                warnings.append("No force field has parameters for this molecule, so the generated geometry is the raw ETKDG embedding.")
            warnings.append("The geometry was generated by the service, not supplied; results refer to that geometry.")
        ident = identity(parsed.mol)
        symbols = [atom.GetSymbol() for atom in full.GetAtoms()]
        numbers = [atom.GetAtomicNum() for atom in full.GetAtoms()]
        positions = np.asarray(full.GetConformer(conf_id).GetPositions(), dtype=float)
        default_charge = ident["formal_charge"]
        default_multiplicity = ident["radical_electrons"] + 1
        input_atoms = parsed.mol.GetNumAtoms()
        atom_meta = [
            {"formal_charge": atom.GetFormalCharge(), "isotope": atom.GetIsotope() or None, "added_hydrogen": atom.GetIdx() >= input_atoms}
            for atom in full.GetAtoms()
        ]
        if any(atom.GetIsotope() for atom in full.GetAtoms()):
            warnings.append("Isotope labels do not affect an electronic-structure calculation and were ignored.")
        if any(number == 0 for number in numbers):
            raise Unsupported("The structure contains dummy atoms, which have no nucleus to compute.", reasons=["dummy atom (atomic number 0) present"])

    if len(numbers) > 1:
        deltas = positions[:, None, :] - positions[None, :, :]
        distances = np.sqrt((deltas**2).sum(axis=-1))
        distances[np.diag_indices(len(numbers))] = np.inf
        i, j = np.unravel_index(int(np.argmin(distances)), distances.shape)
        if distances[i, j] < _MIN_DISTANCE_ANGSTROM:
            raise TaskFailure(
                "invalid_geometry",
                f"Atoms {i} and {j} are {distances[i, j]:.4f} angstrom apart; nuclei closer than {_MIN_DISTANCE_ANGSTROM} angstrom are not a valid geometry.",
                {"atom_indices": [int(i), int(j)], "distance_angstrom": float(distances[i, j])},
            )

    charge = job_input.get("charge")
    charge = default_charge if charge is None else int(charge)
    electron_count = sum(numbers) - charge
    if electron_count < 1:
        raise Unsupported(
            f"With total charge {charge:+d} the system has {electron_count} electrons; there is nothing for an electronic-structure method to compute.",
            reasons=["no electrons"],
        )
    multiplicity = job_input.get("multiplicity")
    if multiplicity is None:
        multiplicity = default_multiplicity if default_multiplicity is not None else (1 if electron_count % 2 == 0 else 2)
        if (electron_count - (multiplicity - 1)) % 2 != 0:
            # A charge override changed the electron parity; fall back to the lowest multiplicity that fits.
            multiplicity = 1 if electron_count % 2 == 0 else 2
            warnings.append(f"Multiplicity was not given; {multiplicity} was assumed from the electron count.")
    multiplicity = int(multiplicity)
    unpaired = multiplicity - 1
    if unpaired > electron_count or (electron_count - unpaired) % 2 != 0:
        raise TaskFailure(
            "inconsistent_charge_multiplicity",
            f"A system with {electron_count} electrons (total charge {charge:+d}) cannot have spin multiplicity {multiplicity}.",
            {"electron_count": electron_count, "charge": charge, "multiplicity": multiplicity},
        )
    return PreparedSystem(
        numbers=numbers,
        symbols=symbols,
        positions=positions,
        charge=charge,
        multiplicity=multiplicity,
        electron_count=electron_count,
        geometry=geometry_source,
        atom_meta=atom_meta,
        warnings=warnings,
        software=software,
    )


def frontier_gap_ev(energies_hartree: list[float], occupations: list[float], hartree_to_ev: float) -> float | None:
    """Gap between the highest orbital that is at least half occupied and the lowest that is not."""
    occupied = [e for e, occ in zip(energies_hartree, occupations) if occ >= 0.5]
    empty = [e for e, occ in zip(energies_hartree, occupations) if occ < 0.5]
    if not occupied or not empty:
        return None
    return float((min(empty) - max(occupied)) * hartree_to_ev)
