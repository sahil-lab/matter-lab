-- ---------------------------------------------------------------------------------------------
-- Reactions
-- ---------------------------------------------------------------------------------------------

CREATE TABLE reactions (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name             text NOT NULL CHECK (btrim(name) <> ''),
  reaction_smiles  text NOT NULL CHECK (reaction_smiles LIKE '%>%>%'),
  description      text,
  temperature_k    double precision CHECK (temperature_k >= 0),
  pressure_pa      double precision CHECK (pressure_pa >= 0),
  solvent_id       uuid REFERENCES solvents (id) ON DELETE SET NULL,
  catalyst_id      uuid REFERENCES catalysts (id) ON DELETE SET NULL,
  conditions       jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(conditions) = 'object'),
  balanced         boolean NOT NULL,
  evidence_level   text NOT NULL CHECK (evidence_level IN ('reference', 'computed', 'rule-based', 'illustrative', 'user-input', 'unsupported')),
  derived_by       jsonb NOT NULL CHECK (jsonb_typeof(derived_by) = 'object'),
  source_id        bigint NOT NULL REFERENCES data_sources (id),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE reactions IS 'Reactions as reaction SMILES (reactants>agents>products), validated and canonicalised by RDKit.';
COMMENT ON COLUMN reactions.temperature_k IS 'Reaction temperature in kelvin, when stated.';
COMMENT ON COLUMN reactions.pressure_pa IS 'Reaction pressure in pascal, when stated.';
COMMENT ON COLUMN reactions.balanced IS 'True when every element and the total charge balance between reactants and products (computed by the service).';
COMMENT ON COLUMN reactions.evidence_level IS 'How the reaction record was obtained (same vocabulary as the frontend EvidenceLevel type).';

CREATE INDEX reactions_name_lower_idx ON reactions (lower(name));
CREATE INDEX reactions_solvent_id_idx ON reactions (solvent_id);
CREATE INDEX reactions_catalyst_id_idx ON reactions (catalyst_id);
CREATE INDEX reactions_source_id_idx ON reactions (source_id);

CREATE TRIGGER reactions_set_updated_at BEFORE UPDATE ON reactions
  FOR EACH ROW EXECUTE FUNCTION matterlab_set_updated_at();

CREATE TABLE reaction_participants (
  reaction_id                 uuid     NOT NULL REFERENCES reactions (id) ON DELETE CASCADE,
  role                        text     NOT NULL CHECK (role IN ('reactant', 'agent', 'product')),
  position                    smallint NOT NULL CHECK (position >= 0),
  canonical_smiles            text     NOT NULL CHECK (canonical_smiles <> ''),
  inchikey                    text     CHECK (inchikey ~ '^[A-Z]{14}-[A-Z]{10}-[A-Z]$'),
  molecular_formula           text     NOT NULL,
  stoichiometric_coefficient  integer  NOT NULL CHECK (stoichiometric_coefficient > 0),
  compound_id                 uuid     REFERENCES compounds (id) ON DELETE SET NULL,
  PRIMARY KEY (reaction_id, role, position)
);

COMMENT ON TABLE reaction_participants IS 'Species of a reaction, derived by the service from the reaction SMILES.';
COMMENT ON COLUMN reaction_participants.stoichiometric_coefficient IS 'Number of times the species appears on its side of the reaction SMILES.';
COMMENT ON COLUMN reaction_participants.compound_id IS 'Catalogue compound with the same InChIKey, when one exists.';

CREATE INDEX reaction_participants_inchikey_idx ON reaction_participants (inchikey);
CREATE INDEX reaction_participants_compound_id_idx ON reaction_participants (compound_id);
