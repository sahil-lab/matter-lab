-- 0002: chemistry catalogue (compounds, names, functional groups, solvents, catalysts, reactions).
--
-- Structure-derived columns (canonical SMILES, InChI, InChIKey, formula, masses, fingerprints) are
-- always computed by the science service with RDKit; derived_by records the exact versions.
-- Similarity and substructure searches run in the service on these rows. PostgreSQL stores the
-- fingerprints but does not interpret them (no chemistry cartridge is installed).

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------------------------------------
-- Compounds
-- ---------------------------------------------------------------------------------------------

CREATE TABLE compounds (
  id                          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name                        text NOT NULL CHECK (btrim(name) <> ''),
  iupac_name                  text,
  canonical_smiles            text NOT NULL CHECK (canonical_smiles <> ''),
  inchi                       text NOT NULL CHECK (inchi LIKE 'InChI=1%'),
  inchikey                    text NOT NULL CHECK (inchikey ~ '^[A-Z]{14}-[A-Z]{10}-[A-Z]$'),
  molblock                    text NOT NULL CHECK (molblock <> ''),
  molecular_formula           text NOT NULL CHECK (molecular_formula <> ''),
  molecular_weight_g_per_mol  double precision NOT NULL CHECK (molecular_weight_g_per_mol > 0),
  monoisotopic_mass_u         double precision NOT NULL CHECK (monoisotopic_mass_u > 0),
  formal_charge               smallint NOT NULL,
  heavy_atom_count            integer  NOT NULL CHECK (heavy_atom_count >= 0),
  external_ids                jsonb    NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(external_ids) = 'object'),
  morgan_fp                   bytea    NOT NULL,
  pattern_fp                  bytea    NOT NULL,
  fingerprint_params          jsonb    NOT NULL CHECK (jsonb_typeof(fingerprint_params) = 'object'),
  derived_by                  jsonb    NOT NULL CHECK (jsonb_typeof(derived_by) = 'object'),
  source_id                   bigint   NOT NULL REFERENCES data_sources (id),
  source_url                  text,
  source_record               jsonb,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compounds_inchikey_key UNIQUE (inchikey)
);

COMMENT ON TABLE compounds IS 'Compound catalogue. Identity is the standard InChIKey computed by RDKit from the stored structure.';
COMMENT ON COLUMN compounds.canonical_smiles IS 'RDKit canonical isomeric SMILES.';
COMMENT ON COLUMN compounds.molblock IS 'MDL molfile (V2000) with 2D depiction coordinates generated by RDKit; not a 3D geometry.';
COMMENT ON COLUMN compounds.molecular_formula IS 'Molecular formula in Hill notation (RDKit CalcMolFormula).';
COMMENT ON COLUMN compounds.molecular_weight_g_per_mol IS 'Average molecular weight in g/mol from standard atomic weights (RDKit).';
COMMENT ON COLUMN compounds.monoisotopic_mass_u IS 'Monoisotopic (exact) mass in unified atomic mass units (RDKit).';
COMMENT ON COLUMN compounds.formal_charge IS 'Net formal charge in units of the elementary charge.';
COMMENT ON COLUMN compounds.external_ids IS 'Identifiers in other databases, e.g. {"pubchem_cid": 2244}.';
COMMENT ON COLUMN compounds.morgan_fp IS 'RDKit Morgan bit fingerprint (ExplicitBitVect binary text); parameters in fingerprint_params.';
COMMENT ON COLUMN compounds.pattern_fp IS 'RDKit pattern fingerprint used to pre-screen substructure queries.';
COMMENT ON COLUMN compounds.derived_by IS 'Engine and versions that computed the structure-derived columns.';
COMMENT ON COLUMN compounds.source_record IS 'The record exactly as retrieved from the source, kept for traceability.';

CREATE INDEX compounds_molecular_formula_idx ON compounds (molecular_formula);
CREATE INDEX compounds_name_lower_idx ON compounds (lower(name));
CREATE INDEX compounds_external_ids_idx ON compounds USING gin (external_ids jsonb_path_ops);
CREATE INDEX compounds_source_id_idx ON compounds (source_id);

CREATE TRIGGER compounds_set_updated_at BEFORE UPDATE ON compounds
  FOR EACH ROW EXECUTE FUNCTION matterlab_set_updated_at();

CREATE TABLE compound_synonyms (
  compound_id      uuid    NOT NULL REFERENCES compounds (id) ON DELETE CASCADE,
  name             text    NOT NULL CHECK (btrim(name) <> ''),
  name_normalized  text    GENERATED ALWAYS AS (lower(btrim(name))) STORED,
  kind             text    NOT NULL CHECK (kind IN ('preferred', 'iupac', 'query', 'synonym')),
  position         integer NOT NULL DEFAULT 0 CHECK (position >= 0),
  PRIMARY KEY (compound_id, name_normalized)
);

COMMENT ON TABLE compound_synonyms IS 'Names under which a compound can be looked up (case-insensitive exact match on name_normalized).';
COMMENT ON COLUMN compound_synonyms.kind IS 'preferred = display name, iupac = IUPAC name, query = name used to resolve the record at the source, synonym = other name listed by the source.';

CREATE INDEX compound_synonyms_name_idx ON compound_synonyms (name_normalized);
CREATE INDEX compound_synonyms_name_trgm_idx ON compound_synonyms USING gin (name_normalized gin_trgm_ops);

-- ---------------------------------------------------------------------------------------------
-- Functional groups (SMARTS definitions)
-- ---------------------------------------------------------------------------------------------

CREATE TABLE functional_groups (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  group_set    text    NOT NULL CHECK (group_set ~ '^[a-z0-9][a-z0-9-]*$'),
  key          text    NOT NULL CHECK (btrim(key) <> ''),
  name         text    NOT NULL CHECK (btrim(name) <> ''),
  smarts       text    NOT NULL CHECK (smarts <> ''),
  description  text,
  parent_key   text,
  position     integer NOT NULL DEFAULT 0 CHECK (position >= 0),
  source_file  text,
  source_id    bigint  NOT NULL REFERENCES data_sources (id),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT functional_groups_set_key_key UNIQUE (group_set, key)
);

COMMENT ON TABLE functional_groups IS 'Functional-group definitions as SMARTS patterns, grouped into named sets.';
COMMENT ON COLUMN functional_groups.group_set IS 'Definition set the pattern belongs to, e.g. rdkit-fragment-descriptors.';
COMMENT ON COLUMN functional_groups.parent_key IS 'Key of the parent definition within the same set, for hierarchical sets.';
COMMENT ON COLUMN functional_groups.source_file IS 'File in the source distribution that the definition was read from.';

CREATE INDEX functional_groups_source_id_idx ON functional_groups (source_id);

CREATE TRIGGER functional_groups_set_updated_at BEFORE UPDATE ON functional_groups
  FOR EACH ROW EXECUTE FUNCTION matterlab_set_updated_at();

-- ---------------------------------------------------------------------------------------------
-- Solvents and catalysts (names, identifiers and structures; properties only when actually sourced)
-- ---------------------------------------------------------------------------------------------

CREATE TABLE solvents (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name               text NOT NULL CHECK (btrim(name) <> ''),
  compound_id        uuid REFERENCES compounds (id) ON DELETE SET NULL,
  canonical_smiles   text,
  inchi              text,
  inchikey           text CHECK (inchikey ~ '^[A-Z]{14}-[A-Z]{10}-[A-Z]$'),
  molecular_formula  text,
  molblock           text,
  structure_status   text NOT NULL CHECK (structure_status IN ('rdkit-validated', 'source-only', 'none')),
  structure_notes    text,
  external_ids       jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(external_ids) = 'object'),
  properties         jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(properties) = 'array'),
  derived_by         jsonb CHECK (jsonb_typeof(derived_by) = 'object'),
  source_id          bigint NOT NULL REFERENCES data_sources (id),
  source_url         text,
  source_record      jsonb,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT solvents_validated_has_identifiers CHECK (
    structure_status <> 'rdkit-validated'
    OR (canonical_smiles IS NOT NULL AND inchikey IS NOT NULL AND molecular_formula IS NOT NULL AND derived_by IS NOT NULL)
  )
);

COMMENT ON TABLE solvents IS 'Common solvents: names, identifiers and structures. No property is stored unless it was retrieved from a cited source.';
COMMENT ON COLUMN solvents.structure_status IS
  'rdkit-validated = identifiers computed by RDKit from the source structure; source-only = RDKit could not sanitise the structure, identifiers are verbatim from the source; none = no structure.';
COMMENT ON COLUMN solvents.properties IS 'Array of {name, value, unit, evidence, source} objects; only values actually retrieved from a source.';

CREATE UNIQUE INDEX solvents_name_lower_key ON solvents (lower(name));
CREATE INDEX solvents_inchikey_idx ON solvents (inchikey);
CREATE INDEX solvents_compound_id_idx ON solvents (compound_id);
CREATE INDEX solvents_source_id_idx ON solvents (source_id);

CREATE TRIGGER solvents_set_updated_at BEFORE UPDATE ON solvents
  FOR EACH ROW EXECUTE FUNCTION matterlab_set_updated_at();

